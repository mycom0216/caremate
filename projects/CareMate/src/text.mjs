// ─────────────────────────────────────────────────────────────────────────────
// text.mjs — 한국어 텍스트 처리 도구 (토큰화·문장 분리·개인정보 마스킹)
//
// [왜 필요한가]  검색(BM25)·분류(나이브 베이즈)·답변 검증은 모두 "글자 덩어리(토큰)의 겹침"으로 동작합니다.
//               이 파일이 문장을 토큰으로 바꾸는 규칙을 한 곳에서 정하므로, 검색과 검증이 같은 기준을 씁니다.
//
// [토큰화 방식]  형태소 분석기(외부 라이브러리)를 쓰지 않고 두 가지를 합칩니다.
//    ① 어절 토큰  'w:반품'   조사를 뗀 어절 전체
//    ② 글자 바이그램 'b:반품' 어절 안의 인접한 두 글자 쌍. (한 글자 어절은 'c:글자')
//    한국어는 "반품이/반품은/반품하려면"처럼 어미·조사가 붙어 모양이 바뀝니다. 두 글자씩 잘라 두면
//    조사가 달라도 '반품' 바이그램이 공통으로 남아서 검색에 견딥니다.
//    토큰 앞 접두사(w:/b:/c:)는 종류를 구분하기 위한 표시이며, 다른 파일에서 t[0]==='b' 로 바이그램만 골라 씁니다.
//
// [개인정보(PII) 마스킹]  전화·이메일·카드·주민번호를 저장하기 전에 가려서, DB 와 LLM 에는 원본이 들어가지 않게 합니다.
// ─────────────────────────────────────────────────────────────────────────────
// 한국어 질의·문서용 가벼운 토크나이저: 어절 + 어절 내부 문자 바이그램.
// 형태소 분석기 없이도 조사·어미 변화("반품이/반품은/반품하려면")에 견디도록 바이그램을 씁니다.
// 끝에 붙은 조사·어미를 떼기 위한 정규식. $ 는 "어절의 끝", | 는 "또는"입니다. 정규식은 문자열 앞쪽에서
//   시작하는 일치를 먼저 찾으므로 '인가요'처럼 긴 접미사가 끝의 '요'보다 우선해서 떼어집니다. 한 번에 한 개의 접미사만 제거합니다.
//   (단순 규칙이라 단어의 일부인 마지막 글자가 잘리는 경우도 있을 수 있지만, 질의와 문서에 같은 규칙을 적용하므로 검색에는 큰 문제가 없습니다.)
const JOSA = /(으로|에서|에게|까지|부터|이나|이랑|인가요|나요|까요|은|는|이|가|을|를|에|로|의|도|만|과|와|요)$/u;

// 텍스트 정규화: 문자열이 아니면 빈 문자열로, NFKC(전각 문자·호환 문자를 표준 글자로), 소문자화, 연속 공백을 한 칸으로, 앞뒤 공백 제거.
//   같은 뜻의 글자가 다른 모양이라 검색에서 놓치는 일을 줄입니다.
export function normalize(text) {
  return String(text ?? '').normalize('NFKC').toLowerCase().replace(/\s+/gu, ' ').trim();
}

// 어절 목록: 정규화한 뒤 글자(\p{L})·숫자(\p{N})가 이어진 덩어리만 뽑습니다. 구두점·기호는 버려집니다. 없으면 빈 배열.
export function words(text) {
  return normalize(text).match(/[\p{L}\p{N}]+/gu) ?? [];
}

// 질의 전용 군말 목록: "알려줘", "어때", "되나요" 같은 요청·어미 표현은 검색에 도움이 안 되므로 질의에서 빼서
//   이런 말 때문에 엉뚱한 문서가 높은 점수를 받거나, 반대로 신뢰도가 떨어지는 일을 막습니다. (문서 쪽에는 적용하지 않음)
// 질의 전용: 의미 없는 군말·요청 어미("알려줘", "어때", "되나요")는 검색 근거에서 뺍니다.
export const FILLER = new Set(['알려줘', '알려주세요', '알려줄래', '해줘', '해주세요', '줄래', '어때', '어떻게', '어떡해', '되나요', '돼요', '있나요', '있어요', '가능한가요', '가능해요', '궁금해요', '궁금합니다', '싶어요', '싶은데', '하나요', '할까요', '인가요', '이에요', '예요', '뭐야', '뭔가요', '무엇인가요', '좀', '혹시', '그냥', '정말', '진짜', '너', '나', '저', '제가', '저는', '내가']);

// 토큰화 본체. 반환: ['w:반품', 'b:반품', ...] 같은 문자열 배열.
//   query:true 이면 FILLER 에 있는 어절을 건너뜁니다.
export function tokens(text, { query = false } = {}) {
  const out = [];
  for (const w of words(text)) {
    // 질의(query:true)일 때 군말 어절은 건너뜁니다.
    if (query && FILLER.has(w)) continue;
    // 어절이 3글자 이상일 때만 조사를 뗍니다(2글자 이하는 조사가 아니라 단어 자체일 가능성이 높음). 예: '반품을' → '반품'.
    const stem = w.length > 2 ? w.replace(JOSA, '') : w;
    // 뗀 결과(어근)가 2글자 이상이면 어절 토큰 w: 로 추가합니다.
    if (stem.length >= 2) out.push('w:' + stem);
    // [...stem] 은 글자 단위 배열(이모지 같은 특수문자도 안전하게 쪼갬). 한 글자면 c: 토큰, 두 글자 이상이면 인접한 두 글자마다 b: 바이그램을 만듭니다.
    //   예: '배송비' → b:배송, b:송비.
    const chars = [...stem];
    if (chars.length === 1) out.push('c:' + chars[0]);
    for (let i = 0; i + 1 < chars.length; i++) out.push('b:' + chars[i] + chars[i + 1]);
  }
  return out;
}

// 문장 분리: 마침표·느낌표·물음표 뒤의 공백에서 자릅니다((?<=...)는 앞 글자를 소비하지 않는 "뒤돌아보기"라 구두점이 문장에 남음).
//   추출형 답변이 원문 문장을 그대로 골라 보여 줄 때 씁니다(llm.mjs).
export function sentences(text) {
  return String(text).split(/(?<=[.!?])\s+/u).map((s) => s.trim()).filter(Boolean);
}

// 개인정보 마스킹. 반환: { masked: 가려진 문자열, found: ['전화번호', ...] (발견된 종류, 중복 없음) }
//   호출하는 쪽(chat.mjs)은 masked 만 저장·LLM 전달에 쓰고, found 는 화면에 "개인정보를 감지해 가렸습니다"로 알립니다.
// 개인정보(전화·이메일·카드·주민번호)를 저장·LLM 전달 전에 가립니다.
export function maskPII(text) {
  const found = [];
  let masked = String(text ?? '');
  // 규칙 목록 [종류 이름, 정규식, 대체 문구]. 위에서부터 차례로 적용합니다.
  //   긴 숫자 형식(주민번호 13자리, 카드 16자리)을 먼저 가려야 마지막 전화번호 규칙이 그 일부 숫자를 잘못 잡지 않습니다.
  //   \b 는 단어 경계, \d 는 숫자, {n} 은 n번 반복, [- ]? 는 하이픈 또는 공백이 0~1개(하이픈 없이 붙여 쓴 번호도 잡음)입니다.
  //   · 주민등록번호: 숫자 6자리 + 성별 자리 1~4 + 숫자 6자리 (예: 900101-1234567)
  //   · 카드번호: 숫자 4자리 묶음 4개
  //   · 전화번호: 0으로 시작하는 지역/통신 번호 + 3~4자리 + 4자리
  //   · 이메일: 영문·숫자·._+- 로 된 아이디 @ 도메인.최상위
  const rules = [
    ['주민등록번호', /\b\d{6}[- ]?[1-4]\d{6}\b/gu, '[주민번호]'],
    ['카드번호', /\b(?:\d{4}[- ]?){3}\d{4}\b/gu, '[카드번호]'],
    ['전화번호', /\b0\d{1,2}[- ]?\d{3,4}[- ]?\d{4}\b/gu, '[전화번호]'],
    ['이메일', /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/gu, '[이메일]'],
  ];
  // 각 규칙을 적용해 바뀐 것이 있으면(next !== masked) 그 종류를 found 에 기록하고 결과를 이어서 다음 규칙에 넘깁니다.
  for (const [name, re, repl] of rules) {
    const next = masked.replace(re, repl);
    if (next !== masked) { found.push(name); masked = next; }
  }
  return { masked, found };
}
